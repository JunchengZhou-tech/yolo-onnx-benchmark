import time
import numpy as np
from ultralytics import YOLO

def main():
    # 1. Initialize the standard PyTorch model (YOLOv8 Nano for speed)
    print("Loading PyTorch model...")
    pt_model = YOLO("yolov8n.pt")

    # 2. Export to ONNX with FP16 quantization
    # half=True compresses the model weights to 16-bit floats
    print("Exporting to ONNX (FP16)...")
    onnx_path = pt_model.export(format="onnx", half=True)
    print(f"Exported ONNX model to: {onnx_path}")

    # 3. Load the newly exported ONNX model
    print("Loading ONNX model into runtime...")
    onnx_model = YOLO(onnx_path)

    # 4. Create a dummy image array (640x640 RGB) for standardized testing
    # In a real scenario, you can replace this with cv2.imread("test_image.jpg")
    dummy_image = np.zeros((640, 640, 3), dtype=np.uint8)

    def benchmark_model(model, image, model_name, iterations=100):
        print(f"\n--- Benchmarking {model_name} ---")

        # WARM-UP: Run the model a few times before timing.
        # This initializes CUDA/CPU memory and avoids skewed first-run latency.
        print("Warming up engine...")
        for _ in range(10):
            _ = model(image, verbose=False)

        # BENCHMARK LOOP
        print(f"Running {iterations} inference iterations...")
        start_time = time.perf_counter()

        for _ in range(iterations):
            _ = model(image, verbose=False)

        end_time = time.perf_counter()

        # Calculate metrics
        total_time = end_time - start_time
        avg_time_ms = (total_time / iterations) * 1000
        fps = 1000 / avg_time_ms

        print(f"Average inference time: {avg_time_ms:.2f} ms")
        print(f"Throughput: {fps:.2f} FPS")

        return avg_time_ms, fps

    # 5. Run the head-to-head comparison
    pt_ms, pt_fps = benchmark_model(pt_model, dummy_image, "PyTorch (FP32)")
    onnx_ms, onnx_fps = benchmark_model(onnx_model, dummy_image, "ONNX (FP16)")

    # 6. Output the final summary metrics
    print("\n=== FINAL BENCHMARK SUMMARY ===")
    print(f"Latency Drop: {pt_ms:.2f}ms -> {onnx_ms:.2f}ms")
    if pt_fps > 0:
        speedup = ((onnx_fps - pt_fps) / pt_fps) * 100
        print(f"Throughput Increase: +{speedup:.1f}%")

if __name__ == "__main__":
    main()